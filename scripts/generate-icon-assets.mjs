/**
 * Regenerates icon browsing assets from @twistify/react-icons.
 *
 * Home previews are static SVG, not named ESM imports. Category pages
 * dynamic-import() each set as a namespace, and webpack treats that as using
 * every export. A static named import of the same module would then ship the
 * whole set. SVG rendered from the real components (size 20) keeps the home
 * page off that graph and matches the previous cards.
 *
 * Icon names are sorted by UTF-16 code unit, which is the order webpack used
 * when the old pages enumerated a module namespace with Object.keys.
 *
 * Run: npm run generate-icons
 */
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { IconsManifest } = require('@twistify/react-icons')

const CHROME = [
  'AiGithubOutlined',
  'TiLogoGithubFilled',
  'TiSunny',
  'TiModeDark',
  'RaCheck',
  'RaCopy',
]

function exportNames(id) {
  const source = readFileSync(
    join(root, 'node_modules/@twistify/react-icons', id, 'index.mjs'),
    'utf8'
  )
  return [...source.matchAll(/^export function (\w+)/gm)].map((match) => match[1])
}

function splitSvg(html) {
  const match = html.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/)
  if (!match) throw new Error(`Unexpected svg markup: ${html.slice(0, 120)}`)
  const attrs = {}
  for (const attr of match[1].matchAll(/([\w:-]+)="([^"]*)"/g)) {
    attrs[attr[1]] = attr[2]
  }
  return { attrs, inner: match[2] }
}

const sets = []
const searchIndex = []

for (const { id, name } of IconsManifest) {
  const names = exportNames(id).sort((a, b) => a < b ? -1 : a > b ? 1 : 0)
  const mod = require(`@twistify/react-icons/${id}`)
  if (names.length !== Object.keys(mod).length) {
    throw new Error(`Export count mismatch for ${id}`)
  }

  const icons = names.slice(0, 9).map((iconName) => (
    renderToStaticMarkup(React.createElement(mod[iconName], { size: 20 }))
  ))

  sets.push({ id, name, len: names.length, icons })
  for (const iconName of names) searchIndex.push([id, iconName])
}

sets.sort((a, b) => a.name.localeCompare(b.name))

const previewFile = `/* Generated by scripts/generate-icon-assets.mjs. Do not edit. */
export type HomePreviewSet = {
  id: string
  name: string
  len: number
  icons: string[]
}

export const homePreviewSets: HomePreviewSet[] = ${JSON.stringify(sets, null, 2)}
`

const modules = new Map(IconsManifest.map(({ id }) => [id, require(`@twistify/react-icons/${id}`)]))
const chrome = CHROME.map((iconName) => {
  const mod = [...modules.values()].find((entry) => typeof entry[iconName] === 'function')
  if (!mod) throw new Error(`Missing chrome icon ${iconName}`)
  const html = renderToStaticMarkup(React.createElement(mod[iconName]))
  const { attrs, inner } = splitSvg(html)
  return { iconName, viewBox: attrs.viewBox, inner }
})

const chromeFile = `/* Generated by scripts/generate-icon-assets.mjs. Do not edit. */
import type { SVGProps } from 'react'

type ChromeIconProps = SVGProps<SVGSVGElement>

function ChromeIcon({
  viewBox,
  html,
  className,
  ...props
}: ChromeIconProps & { viewBox: string; html: string }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={viewBox}
      width="1em"
      height="1em"
      className={className}
      {...props}
      dangerouslySetInnerHTML={{ __html: html }}
    />
  )
}

${chrome.map(({ iconName, viewBox, inner }) => `export function ${iconName}(props: ChromeIconProps) {
  return <ChromeIcon {...props} viewBox={${JSON.stringify(viewBox)}} html={${JSON.stringify(inner)}} />
}`).join('\n\n')}
`

const loaderFile = `/* Generated by scripts/generate-icon-assets.mjs. Do not edit. */
import type { IconType } from '@twistify/react-icons'

export type IconModule = Record<string, IconType>

export const iconLoaders: Record<string, () => Promise<IconModule>> = {
${IconsManifest.map(({ id }) => `  ${JSON.stringify(id)}: () => import(/* webpackChunkName: ${JSON.stringify(`icons-${id}`)} */ '@twistify/react-icons/${id}') as unknown as Promise<IconModule>,`).join('\n')}
}
`

mkdirSync(join(root, 'generated'), { recursive: true })
mkdirSync(join(root, 'public'), { recursive: true })
const idsFile = `/* Generated by scripts/generate-icon-assets.mjs. Do not edit. */
export const iconIds = ${JSON.stringify(IconsManifest.map(({ id }) => id))}
`
writeFileSync(join(root, 'generated/icon-ids.ts'), idsFile)
writeFileSync(join(root, 'generated/home-previews.ts'), previewFile)
writeFileSync(join(root, 'generated/chrome-icons.tsx'), chromeFile)
writeFileSync(join(root, 'generated/icon-loaders.ts'), loaderFile)
writeFileSync(join(root, 'public/icon-search-index.json'), JSON.stringify(searchIndex))

const previewBytes = Buffer.byteLength(previewFile)
const indexBytes = Buffer.byteLength(JSON.stringify(searchIndex))
console.log(`sets ${sets.length}`)
console.log(`icons ${searchIndex.length}`)
console.log(`home previews ${previewBytes} bytes`)
console.log(`search index ${indexBytes} bytes`)
for (const set of sets) console.log(`${String(set.len).padStart(6)}  ${set.icons.length} previews  ${set.name}`)
